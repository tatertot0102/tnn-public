// Recover application declarations from the preserved deployed artifact, excluding
// bundled vendors. Input is code evidence, not executed by this generator.
// Usage: node scripts/recover-live-bundle.cjs bundle.js src/recovered/live-module.jsx
const fs = require('node:fs')
const crypto = require('node:crypto')
const parser = require('@babel/parser')
const traverse = require('@babel/traverse').default
const generate = require('@babel/generator').default
const source = fs.readFileSync(process.argv[2], 'utf8')
const ast = parser.parse(source, { sourceType: 'module' })
let program
traverse(ast, { Program(p) { program = p; p.stop() } })
const external = new Map(Object.entries({
  x: 'React', o: 'jsxRuntime', W: 'supabase', Q: 'Link', xa: 'NavLink',
  Xt: 'useNavigate', Ot: 'useLocation', ac: 'useParams', oc: 'useSearchParams',
  qw: 'BrowserRouter', Uw: 'Routes', fe: 'Route', sr: 'Navigate',
  Gx: 'InfoPage', jh: 'CreatorPage', Fh: 'TeamPage', Kn: 'AutoThumbnail',
}))
const included = new Map(), icons = new Map()
function visit(name) {
  if (external.has(name) || included.has(name) || icons.has(name)) return
  const binding = program.scope.getBinding(name)
  if (!binding) return
  const path = binding.path
  if (path.isVariableDeclarator() && path.node.init?.type === 'CallExpression' && path.node.init.callee.name === 'H' && path.node.init.arguments[0]?.type === 'StringLiteral') {
    icons.set(name, path.node.init.arguments[0].value); return
  }
  included.set(name, path)
  path.traverse({ ReferencedIdentifier(reference) {
    const dependency = reference.scope.getBinding(reference.node.name)
    if (dependency && (dependency.path.node.start < path.node.start || dependency.path.node.end > path.node.end)) visit(reference.node.name)
  } })
}
visit('_k')
const imports = `import * as x from 'react'
import * as o from 'react/jsx-runtime'
import { BrowserRouter as qw, Routes as Uw, Route as fe, Navigate as sr, Link as Q, NavLink as xa, useNavigate as Xt, useLocation as Ot, useParams as ac, useSearchParams as oc } from 'react-router-dom'
import { supabase as W } from '../lib/supabase'
import Gx from '../pages/public/InfoPage'
import jh from '../pages/public/CreatorPage'
import Fh from '../pages/newsroom/TeamPage'
import { AutoThumbnail as Kn } from '../components/public/AutoThumbnail'
import { ${[...icons].map(([alias, name]) => `${name} as ${alias}`).join(', ')} } from 'lucide-react'
`
const declarations = [...included.values()].sort((a,b) => a.node.start - b.node.start).map(path => {
  return path.isVariableDeclarator() ? `${path.parent.kind} ${generate(path.node, { comments: false }).code};` : generate(path.node, { comments: false }).code
})
const exportStatement = `export { _k as default, Ax as HomePage, Sh as VideosPage, Yx as StoryPage, Xx as LoginPage, Ra as AdminLayout, Br as PublicLayout, Oh as DashboardPage, Uh as VideoCMSPage, Fb as AuthProvider, Gr as useAuth, jt as ProtectedRoute }\n`
const header = `// Reconstructed directly from deployed bundle SHA-256 ${crypto.createHash('sha256').update(source).digest('hex')}.
// Generated by scripts/recover-live-bundle.cjs. Compiled identifier names and JSX
// runtime calls are retained deliberately: no missing behavior is guessed.
// See docs/recovery/PROVENANCE.md for source and verification limits.\n`
fs.writeFileSync(process.argv[3], header + imports + declarations.join('\n\n') + '\n' + exportStatement)
console.log(`Recovered ${included.size} application declarations; mapped ${icons.size} icons to the installed icon library.`)
